// Deliberately no dotenv or static Payload/config imports: refuse BEFORE any config initialization.
import { realpathSync } from 'node:fs'
import { assertIsolatedE2E } from '../src/lib/e2e-isolation'

const { database, uploads } = assertIsolatedE2E()
const email = process.env.E2E_ADMIN_EMAIL
const password = process.env.E2E_ADMIN_PASSWORD
if (!email?.endsWith('@example.test') || !password || password.length < 32) {
  throw new Error('Isolated E2E credentials are required (generated by playwright.isolated.config.ts).')
}
const { getPayload } = await import('payload')
const config = (await import('../src/payload.config')).default
const payload = await getPayload({ config })
try {
  // Check the actual connection as well as env/config, before creating a privileged user.
  const dbs = await payload.db.drizzle.$client.execute('PRAGMA database_list')
  const main = dbs.rows.find((row) => row.name === 'main')?.file
  if (!main || realpathSync(String(main)) !== database ||
    realpathSync(payload.collections.media.config.upload.staticDir!) !== uploads) {
    throw new Error('Payload did not open the isolated E2E paths; refusing to seed.')
  }
  await payload.create({
    collection: 'users',
    overrideAccess: true,
    data: { email, password, roles: ['admin'], enableAPIKey: false },
  })
} finally {
  await payload.destroy()
}
